export function findReciter(idOrSlug: string | number): ReciterInfo {
  const raw = String(idOrSlug).trim().toLowerCase();
  const num = Number(raw);
  const byId = !Number.isNaN(num) ? RECITERS_CATALOG.find((r) => r.id === num) : undefined;
  if (byId) return byId;
  const bySlug = RECITERS_CATALOG.find(
    (r) =>
      r.slug.toLowerCase() === raw ||
      r.kalamalahSlug?.toLowerCase() === raw ||
      r.islamOnlineTimingSlug?.toLowerCase() === raw
  );
  return bySlug ?? RECITERS_CATALOG[0]!;
}

export function getSurahAudioUrl(reciter: ReciterInfo, surahNumber: number): string {
  const padded = String(surahNumber).padStart(3, '0');
  if (reciter.kalamalahSlug && reciter.audioBaseUrl.includes('api.kalamalah.com/api/')) {
    return `https://api.kalamalah.com/api/${reciter.kalamalahSlug}/murattal/${padded}`;
  }
  if (reciter.slug === 'abu-bakr-al-shatri') {
    return `https://server11.mp3quran.net/shatri/${padded}.mp3`;
  }
  if (reciter.audioBaseUrl.includes('api.kalamalah.com/api/')) {
    return `${reciter.audioBaseUrl}/${padded}`;
  }
  return `${reciter.audioBaseUrl}/${padded}.mp3`;
}

export function getSurahFallbackAudioUrl(reciter: ReciterInfo, surahNumber: number): string {
  const padded = String(surahNumber).padStart(3, '0');
  if (reciter.islamOnlineTimingSlug) {
    return `https://cdn.islam-online.net/data/full/${reciter.islamOnlineTimingSlug}/${padded}.mp3`;
  }
  return `https://cdn.islam-online.net/data/full/${reciter.slug}/${padded}.mp3`;
}

export function getReciterPhotoUrl(reciter: ReciterInfo): string {
  if (reciter.photoUrl) return reciter.photoUrl;
  if (reciter.kalamalahSlug) {
    return `https://api.kalamalah.com/api/reciter-profile/${reciter.kalamalahSlug}`;
  }
  return `https://quran.islamonline.net/data/profile/${reciter.id}.jpg`;
}
